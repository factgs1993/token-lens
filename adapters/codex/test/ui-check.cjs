const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const { createReportServer } = require('../src/report.cjs');
const usage = { input_tokens: 12000, cached_input_tokens: 8000, output_tokens: 900, reasoning_output_tokens: 200, total_tokens: 12900 };
const first = { id: 'turn-1', label: '<img src=x onerror="alert(1)">', prompt: { preview: '</script><img src=x onerror="alert(1)">', length: 321, truncated: true }, hasUsage: true, status: 'completed', usage, requests: [{ at: '2026-11-10T10:00:00Z', model: 'test-model', ...usage }], categories: { schemas: 1000, instructions: 2000, conversation: 3000, tool_results: 5000, tool_calls: 300 }, consumers: { exec: 4500, web: 500 } };
const second = { ...first, id: 'turn-2', label: 'Второй запрос', prompt: { preview: 'Второй запрос', length: 13, truncated: false }, usage: { ...usage, input_tokens: 100, cached_input_tokens: 50, output_tokens: 25, total_tokens: 125 } };
const missing = { ...first, id: 'turn-3', label: 'Нет счётчиков', prompt: null, hasUsage: false, status: 'running', requests: [] };
const fixture = { schemaVersion: 1, exportedAt: '2026-11-11T10:00:00Z', sessionId: 'session-1', turnId: 'turn-1', source: 'token_usage_record', malformedLines: 0, turns: [first, second, missing], summary: { totals: { input_tokens: 12100, output_tokens: 925, total_tokens: 13025 }, turnCount: 3, measuredTurnCount: 2, missingUsageTurns: 1, runningTurns: 1 } };
(async () => {
  const browser = await chromium.launch({ headless: true });
  let server;
  try {
    for (const [width, theme] of [[375, 'dark'], [768, 'light'], [1440, 'dark']]) {
      const page = await browser.newPage({ viewport: { width, height: 1400 }, colorScheme: theme });
      const errors = []; page.on('pageerror', error => errors.push(error.message));
      await page.setContent('<style>body{margin:0}iframe{width:100%;height:1380px;border:0}</style><iframe></iframe>');
      await page.evaluate(({ html, fixture, theme }) => {
        window.calls = [];
        window.addEventListener('message', event => {
          const message = event.data;
          if (!message?.method || message.id === undefined) return;
          let result = {};
          if (message.method === 'ui/initialize') result = { protocolVersion: '2026-01-26', hostInfo: { name: 'Codex', version: '26.1029.61003' }, hostCapabilities: { serverTools: {} }, hostContext: { theme, 'openai/deepLink': { url: '/answer?sessionId=session-1&turnId=turn-1' } } };
          if (message.method === 'tools/call') { window.calls.push(message.params); result = { content: [], structuredContent: { report: fixture, baseUrl: null } }; }
          event.source.postMessage({ jsonrpc: '2.0', id: message.id, result }, '*');
        });
        document.querySelector('iframe').srcdoc = html;
      }, { html: fs.readFileSync('dist/panel.html', 'utf8'), fixture, theme });
      const frame = page.frameLocator('iframe');
      await frame.locator('#total').filter({ hasText: '12 900' }).waitFor({ timeout: 10000 });
      assert.equal(await frame.locator('select').count(), 0);
      assert.equal(await frame.locator('#answer-title img, #prompt-preview img').count(), 0);
      await frame.locator('.prompt > summary').click();
      assert.ok((await frame.locator('#prompt-title').textContent()).includes('321'));
      assert.equal(await frame.locator('#prompt-preview').textContent(), first.prompt.preview);
      assert.equal(await frame.locator('#history').getAttribute('open'), null);
      await frame.locator('#history > summary').click();
      assert.ok((await frame.locator('#chat-coverage').textContent()).includes('2 из 3'));
      await frame.locator('[data-turn-id="turn-2"]').click();
      assert.equal(await frame.locator('#total').textContent(), '125');
      await frame.locator('[data-turn-id="turn-3"]').click();
      assert.equal(await frame.locator('#report').isVisible(), false);
      assert.ok((await frame.locator('#status').textContent()).includes('счётчики ещё не записаны'));
      await frame.locator('#return-answer').click();
      assert.equal((await frame.locator('#total').textContent()).replace(/\s/g, ' '), '12 900');
      assert.equal(await frame.locator('html').evaluate(el => el.scrollWidth > el.clientWidth), false);
      const calls = await page.evaluate(() => window.calls);
      assert.deepEqual(calls[0].arguments, { sessionId: 'session-1', turnId: 'turn-1' });
      assert.equal(calls[0].name, 'read_token_report');
      assert.deepEqual(errors, []);
      await page.screenshot({ path: `test/panel-${width}-${theme}.png`, fullPage: true });
      await page.close();
    }
    server = createReportServer({ snapshot: (sessionId, turnId) => ({ ...fixture, sessionId, turnId }) }, path.join(__dirname, '../dist'));
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const base = `http://127.0.0.1:${server.address().port}`;
    const page = await browser.newPage({ viewport: { width: 1100, height: 1400 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${base}/answer?sessionId=session-1&turnId=turn-1`);
    await page.locator('#total').filter({ hasText: '12 900' }).waitFor();
    first.usage.output_tokens++; first.usage.total_tokens++; fixture.summary.totals.output_tokens++; fixture.summary.totals.total_tokens++;
    await page.locator('#total').filter({ hasText: '12 901' }).waitFor({ timeout: 10000 });
    await page.locator('#history > summary').click();
    await page.locator('[data-turn-id="turn-2"]').click();
    const jsonPending = page.waitForEvent('download'); await page.locator('#download-json').click(); const jsonDownload = await jsonPending;
    assert.equal(JSON.parse(fs.readFileSync(await jsonDownload.path(), 'utf8')).turnId, 'turn-2');
    const htmlPending = page.waitForEvent('download'); await page.locator('#download-html').click(); const htmlDownload = await htmlPending;
    const offlinePath = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'token-lens-offline-')), 'report.html');
    await htmlDownload.saveAs(offlinePath);
    await page.close();
    const offline = await browser.newPage({ viewport: { width: 1100, height: 1400 } });
    const requests = []; offline.on('request', request => requests.push(request.url())); offline.on('pageerror', error => errors.push(error.message));
    await offline.goto(pathToFileURL(offlinePath).href);
    await offline.locator('#total').filter({ hasText: '125' }).waitFor();
    assert.equal(await offline.locator('#live').textContent(), 'Сохранённый отчёт');
    await offline.locator('#history > summary').click(); await offline.locator('[data-turn-id="turn-1"]').click();
    assert.equal((await offline.locator('#total').textContent()).replace(/\s/g, ' '), '12 901');
    await offline.locator('.prompt > summary').click();
    assert.equal(await offline.locator('#prompt-preview img').count(), 0);
    const offlineJson = offline.waitForEvent('download'); await offline.locator('#download-json').click();
    assert.equal(JSON.parse(fs.readFileSync(await (await offlineJson).path(), 'utf8')).turnId, 'turn-1');
    assert.deepEqual(requests.filter(url => /^https?:/.test(url)), []);
    assert.deepEqual(errors, []);
    await offline.screenshot({ path: 'test/panel-standalone.png', fullPage: true });
    await offline.close();
    console.log('PASS UI: MCP binding, prompt safety, history/totals, missing counters, mobile layout, live browser updates, HTML/JSON downloads and offline history without network.');
  } finally { await browser.close(); if (server) await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode = 1; });
